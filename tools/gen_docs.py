#!/usr/bin/env python3
"""Generate docs/PROBES.md from the probe catalog.

Keeping this generated means the coverage table in the documentation cannot
drift away from what the code actually collects.
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from macsiem.evidence import probes as probes_mod  # noqa: E402
from macsiem.rules import loader  # noqa: E402

FULL = {"root": True, "fda": True, "session": True, "macos": True}


def main():
    rulepack = loader.load()
    report = probes_mod.coverage(rulepack.binary_names(), FULL,
                                 {"capture_content": True})
    summary = probes_mod.summarize_coverage(report)

    lines = [
        "# Evidence probes", "",
        "Generated by `tools/gen_docs.py`. Do not edit by hand.", "",
        "MacSIEM never runs the commands documented in the LOOBins corpus -- "
        "roughly 40 of them destroy evidence or disable security controls. "
        "It runs this catalog instead: %d read-only probes (%d executed, %d "
        "native in-process readers)." % (
            len(probes_mod.CATALOG),
            sum(1 for p in probes_mod.CATALOG if p.kind == "exec"),
            sum(1 for p in probes_mod.CATALOG if p.kind == "native")),
        "",
        "## Coverage of the 62 LOOBins", "",
        "| status | count | meaning |", "| --- | --- | --- |",
        "| covered | %d | a read-only invocation or native reader collects for it |"
        % summary.get("covered", 0),
        "| observational_only | %d | the binary only acts, so it is covered by its "
        "execution history plus the artifact state it would have changed |"
        % summary.get("observational_only", 0),
        "| policy_excluded | %d | disabled by privacy configuration |"
        % summary.get("policy_excluded", 0),
        "| unavailable | %d | the host lacks root, Full Disk Access or a GUI session |"
        % summary.get("unavailable", 0),
        "",
        "The same table is written into every bundle manifest under "
        "`loobins_coverage`, computed against the host's real capabilities at "
        "collection time.",
        "",
        "| LOOBin | status | evidence |", "| --- | --- | --- |",
    ]
    for name, entry in sorted(report.items()):
        evidence = ", ".join("`%s`" % p for p in
                             (entry.get("probes") or entry.get("artifact_state") or []))
        note = entry.get("note") or entry.get("reason") or ""
        lines.append("| `%s` | %s | %s%s |" % (
            name, entry["status"], evidence,
            ("<br><sub>%s</sub>" % note) if note else ""))

    lines += ["", "## The catalog", "",
              "Flags: **R** root, **F** Full Disk Access, **S** GUI session, "
              "**C** content capture (privacy tier high).", "",
              "| probe | kind | scope | cost | flags | covers | collects |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    for probe in probes_mod.CATALOG:
        flags = "".join(["R" if probe.needs_root else "",
                         "F" if probe.needs_fda else "",
                         "S" if probe.needs_session else "",
                         "C" if probe.privacy == probes_mod.HIGH else ""]) or "-"
        lines.append("| `%s` | %s | %s | %s | %s | %s | %s |" % (
            probe.id, probe.kind, probe.scope, probe.cost, flags,
            ", ".join("`%s`" % b for b in probe.loobins) or "-", probe.title))

    exceptions = [p for p in probes_mod.CATALOG if p.exception]
    lines += ["", "## Declared safety exceptions", "",
              "Every probe that needs an exemption from a generic guard rule "
              "declares it here, with its justification. There are %d."
              % len(exceptions), ""]
    for probe in exceptions:
        lines.append("- **`%s`** - %s" % (probe.id, probe.exception))

    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "docs", "PROBES.md")
    with open(path, "w") as handle:
        handle.write("\n".join(lines) + "\n")
    print("%s: %d probes, %s" % (path, len(probes_mod.CATALOG), summary))


if __name__ == "__main__":
    main()
